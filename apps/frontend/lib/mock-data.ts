export function generateLogLines(container: string, count = 60): LogLine[] {
  const levels: LogLine['level'][] = ['info', 'info', 'info', 'debug', 'warn', 'info', 'error', 'info']
  const messages = [
    'Handled GET /v1/accounts/442198 in 42ms',
    'Connection pool utilization at 61%',
    'Health check passed',
    'Received SIGTERM, draining connections',
    'Cache miss for key session:8f21a',
    'Retrying upstream request (attempt 2/3)',
    'Rate limit threshold reached for client 10.0.4.12',
    'Queued job process_payout#88213',
    'Completed job process_payout#88213 in 118ms',
    'Slow query detected: 812ms — SELECT * FROM ledger_entries',
    'Failed to reach upstream host registry.deploycore.io',
    'Container memory usage at 512MB / 1024MB',
    'Rotating log file deploycore.log',
    'New connection from 10.0.1.22:54012',
  ]
  // Fixed anchor timestamp (rather than Date.now()) keeps output deterministic
  // between server and client renders, avoiding hydration mismatches.
  const anchor = new Date('2026-09-14T10:15:00Z').getTime()
  return Array.from({ length: count }).map((_, i) => ({
    id: `log-${container}-${i}`,
    timestamp: new Date(anchor - (count - i) * 4000).toISOString().slice(11, 19),
    level: levels[i % levels.length],
    container,
    message: messages[i % messages.length],
  }))
}
