const enrichDeployment = (
  deployment: Omit<Deployment, 'phase' | 'steps' | 'events' | 'failureReason'> & {
    failureReason?: Deployment['failureReason']
  },
): Deployment => {
  const failureReason = deployment.failureReason
  return {
    ...deployment,
    phase: currentPhaseForStatus(deployment.status, failureReason),
    failureReason,
    steps: buildDeploymentSteps(deployment.status, failureReason),
    events: buildDeploymentEvents(deployment.status, deployment.application, failureReason),
  }
}

